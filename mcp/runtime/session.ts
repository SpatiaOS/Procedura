/** Await an artifact from the current coding-agent session. Never launches a model. */
import { createHash, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync, copyFileSync } from "node:fs";
import { join } from "node:path";
import type { CanonicalRequest, LLMEvent } from "@harness/template/llm/protocol";
import type { LLMClient } from "@harness/template/llm";

export type SessionSettings = { run_dir: string; attempt_id: string; call_timeout_seconds: number };
let configured: SessionSettings | undefined;
let sequence = 0;
let serial: Promise<unknown> = Promise.resolve();
const sha = (data: string | Buffer) => createHash("sha256").update(data).digest("hex");
function atomic(path: string, value: unknown) {
  writeFileSync(path + ".tmp", JSON.stringify(value, null, 2) + "\n");
  renameSync(path + ".tmp", path);
}
export function configureSession(settings: SessionSettings) {
  configured = Object.freeze({ ...settings });
  sequence = 0;
  Reflect.set(globalThis, Symbol.for("procedura.mcp.client"), createSessionClient);
}

async function requestArtifact(kind: "artifact" | "reference_image", req: CanonicalRequest, outputPath?: string) {
  if (!configured) throw new Error("Session transport is not configured");
  const settings = configured;
  req.signal?.throwIfAborted();
  if (req.tools?.length) throw new Error("Pipeline tool-use requests are forbidden in the fixed direct workflow");
  for (const message of req.messages) for (const part of message.content) {
    if (!["text", "image", "thinking"].includes(part.kind)) throw new Error(`Unsupported session request content: ${part.kind}`);
    if (part.kind === "image" && !/^image\/(png|jpeg|webp)$/.test(part.mimeType)) throw new Error("Unsupported image MIME type");
  }
  const id = `${settings.attempt_id}-${String(++sequence).padStart(6, "0")}-${randomUUID()}`;
  const dir = join(settings.run_dir, ".cx/calls", id);
  mkdirSync(dir, { recursive: true });
  const created = Date.now();
  const packet = { schema: 1, transport: "session", id, attempt_id: settings.attempt_id, order: sequence, kind,
    created_at: created, deadline_at: created + settings.call_timeout_seconds * 1000,
    model: req.model, system: req.system ?? [], messages: req.messages };
  atomic(join(dir, "request.json"), packet);
  const requestHash = sha(readFileSync(join(dir, "request.json")));
  atomic(join(dir, "ready.json"), { request_sha256: requestHash });
  console.log(`[session] awaiting ${kind} ${id}; call procedura.next_request`);
  try {
    while (true) {
      req.signal?.throwIfAborted();
      const responsePath = join(dir, "submission.json");
      if (existsSync(responsePath)) {
        if (sha(readFileSync(join(dir, "request.json"))) !== requestHash) throw new Error("Session request changed while awaiting response");
        const response = JSON.parse(readFileSync(responsePath, "utf8"));
        if (response.request_id !== id || response.attempt_id !== settings.attempt_id || response.request_sha256 !== requestHash)
          throw new Error("Session submission identity does not match the waiting request");
        if (response.submitted_at > packet.deadline_at) throw new Error("Session artifact was submitted after its deadline");
        let text = "";
        if (kind === "reference_image") {
          const image = join(dir, "submitted.png");
          const bytes = readFileSync(image);
          if (sha(bytes) !== response.artifact_sha256 || !bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10])))
            throw new Error("Invalid submitted reference PNG");
          copyFileSync(image, outputPath!);
          text = outputPath!;
        } else {
          text = response.artifact_text;
          if (typeof text !== "string" || !text.trim() || sha(text) !== response.artifact_sha256)
            throw new Error("Invalid submitted text artifact");
          writeFileSync(join(dir, "response.txt"), text);
        }
        atomic(join(dir, "result.json"), { status: "ok", transport: "session", request_id: id,
          artifact_sha256: response.artifact_sha256, usage: null,
          note: "Generated by the current coding-agent session; per-request token usage is not available" });
        console.log(`[session] received ${id}`);
        return text;
      }
      if (Date.now() >= packet.deadline_at) throw new Error(`Session request timed out after ${settings.call_timeout_seconds}s: ${id}`);
      await new Promise(resolve => setTimeout(resolve, 100));
    }
  } catch (error) {
    atomic(join(dir, "result.json"), { status: "error", transport: "session", error: String(error) });
    throw error;
  }
}

function enqueue<T>(fn: () => Promise<T>): Promise<T> {
  const task = serial.then(fn, fn);
  serial = task.then(() => undefined, () => undefined);
  return task;
}

export function generateInSession(req: CanonicalRequest): Promise<LLMEvent[]> {
  return enqueue(async () => {
    const text = await requestArtifact("artifact", req);
    // The upstream interface requires numeric usage. These zero sentinels mean
    // unavailable, not free inference; durable session evidence records null.
    return [{ kind: "message-start" }, { kind: "text-delta", text },
      { kind: "message-finish", reason: "stop", usage: { input: 0, output: 0 } }] satisfies LLMEvent[];
  });
}

export function createSessionClient(): LLMClient {
  return { async prepare() { throw new Error("No HTTP model request exists in session mode"); },
    async *stream(_route, req) { yield* await generateInSession(req); },
    async generate(_route, req) { return generateInSession(req); } };
}

export function generateSessionReference(opts: { prompt: string; outputPath: string; signal?: AbortSignal }): Promise<string> {
  return enqueue(() => requestArtifact("reference_image", {
    model: { providerId: "current-session", modelId: "current-session" },
    system: [{ text: "Generate exactly one reference PNG using the built-in image generation capability and the exact supplied prompt. Submit its saved path through submit_artifact(image_path=...). If the capability is unavailable, report that limitation; do not substitute APIs or silently switch to text-only." }],
    messages: [{ role: "user", content: [{ kind: "text", text: opts.prompt }] }], signal: opts.signal,
  }, opts.outputPath));
}
